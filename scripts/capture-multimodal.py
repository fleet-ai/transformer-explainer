def digest(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024*1024), b""):
            h.update(chunk)
    return h.hexdigest()


def tensor(name, value, *, rows=None, columns=None, selection=None, shape=None, role=None):
    item = {"name": name, "shape": list(shape or value.shape), "values": value.tolist()}
    for key, val in (("rowLabels", rows), ("columnLabels", columns), ("slice", selection), ("role", role)):
        if val is not None:
            item[key] = val
    if role == "attention":
        item["head"] = 0
    return item


def make_image(kind):
    from PIL import Image, ImageDraw
    size = 224 if kind == "vit" else 512
    image = Image.new("RGB", (size, size), "white")
    draw = ImageDraw.Draw(image)
    s = size/512
    def box(coords):
        return tuple(round(n*s) for n in coords)
    draw.ellipse(box((48, 72, 224, 248)), fill=(220, 35, 45))
    draw.rectangle(box((300, 72, 464, 236)), fill=(35, 105, 220))
    draw.polygon([tuple(round(v*s) for v in point) for point in ((256, 290), (152, 454), (360, 454))], fill=(35, 165, 80))
    path = ROOT/f"static/architectures/{kind}-shapes.png"
    path.parent.mkdir(parents=True,exist_ok=True)
    image.save(path)
    return image, {"src":f"/architectures/{path.name}", "alt":"A red circle, a blue square and a green triangle on white.", "width":size,"height":size,"patchSize":16,"sha256":digest(path),"source":"Deterministic synthetic geometric input generated by scripts/capture-multimodal.py"}


def provenance(kind, snapshot):
    name, revision, filename, sha = MODELS[kind]
    assert digest(snapshot/filename) == sha
    return {"modelId":name,"revision":revision,"weightFile":filename,"weightsSha256":sha,
        "configSha256":digest(snapshot/"config.json"),"captureScript":"scripts/capture-multimodal.py",
        "captureScriptSha256":digest(__file__),"trained":True,"dtype":"float32","device":"cpu",
        "capturedAt":datetime.now(timezone.utc).isoformat(),
        "libraryVersions":{name:importlib.metadata.version(name) for name in ("torch","transformers","huggingface-hub","Pillow")},
        "modelUrl":f"https://huggingface.co/{name}/tree/{revision}"}


def save(document):
    path = ROOT/f"static/architectures/{document['architecture']}.json"
    path.write_text(json.dumps(document,ensure_ascii=False,separators=(",",":"))+"\n")
    print(json.dumps({"output":str(path),"bytes":path.stat().st_size,"result":document["examples"][0]["output"],"verification":document["verification"]}),flush=True)


def capture_vit(snapshot):
    import torch
    from transformers import AutoImageProcessor, AutoModelForImageClassification
    image, image_info = make_image("vit")
    processor = AutoImageProcessor.from_pretrained(snapshot,local_files_only=True,use_fast=False)
    model = AutoModelForImageClassification.from_pretrained(snapshot,local_files_only=True,
                torch_dtype=torch.float32,attn_implementation="eager").eval()
    inputs = processor(images=image,return_tensors="pt")
    baseline = model(**inputs,output_attentions=True,output_hidden_states=True)
    observed, hooks = {}, []
    def hook(key):
        def record(_, args, output):
            observed[key] = (args[0].detach().clone(), output.detach().clone())
        return record
    hooks.append(model.vit.embeddings.patch_embeddings.register_forward_hook(hook("patches")))
    hooks.append(model.vit.layernorm.register_forward_hook(hook("finalnorm")))
    for i, layer in enumerate(model.vit.encoder.layer):
        hooks.append(layer.attention.attention.value.register_forward_hook(hook(f"v-{i}")))
        hooks.append(layer.attention.output.dense.register_forward_hook(hook(f"o-{i}")))
        hooks.append(layer.intermediate.register_forward_hook(hook(f"ff-{i}")))
        hooks.append(layer.output.dense.register_forward_hook(hook(f"down-{i}")))
    traced = model(**inputs,output_attentions=True,output_hidden_states=True)
    for handle in hooks:
        handle.remove()
    labels = ["[CLS]"] + [f"patch {i//14},{i%14}" for i in range(196)]
    patch_labels = labels[1:9]
    probabilities = torch.softmax(traced.logits[0].double(),-1)
    p, ids = probabilities.topk(8)
    predictions = [{"label":model.config.id2label[n],"probability":prob} for n,prob in zip(ids.tolist(),p.tolist())]
    checks = {"hookedVsUnhookedLogitMaxError":(baseline.logits-traced.logits).abs().max().item(),
              "attentionRowSumMaxError":0.,"attentionContextMaxError":0.,
              "classifierProjectionMaxError":0.,"probabilitySumError":abs(probabilities.sum().item()-1)}
    cls = observed["finalnorm"][1][0,0]
    checks["classifierProjectionMaxError"] = (model.classifier(cls)-traced.logits[0]).abs().max().item()
    layers = []
    for i in range(model.config.num_hidden_layers):
        attention = traced.attentions[i][0]
        values = observed[f"v-{i}"][1][0].reshape(197,3,64).transpose(0,1)
        expected = (attention@values).transpose(0,1).reshape(197,192)
        context = observed[f"o-{i}"][0][0]
        checks["attentionContextMaxError"] = max(checks["attentionContextMaxError"],(expected-context).abs().max().item())
        checks["attentionRowSumMaxError"] = max(checks["attentionRowSumMaxError"],(attention.sum(-1)-1).abs().max().item())
        operations = [
            {"id":"patches","label":"16 × 16 image patches","kind":"embedding",
             "description":"The image processor resizes to 224 × 224 and normalizes RGB channels. A learned convolution projects each 16 × 16 RGB patch (768 pixel values) into a 192D token. All 196 patches participate.",
             "formula":"patchᵢ = Wpatch · flatten(RGBᵢ) + bpatch",
             "tensors":[tensor("Projected image patches",observed["patches"][1][0,:8,:4],rows=patch_labels,selection="Patches 0–7 · coordinates 0–3",shape=[196,192])],
             "metrics":[{"label":"Image patches","value":196},{"label":"Patch size","value":"16 × 16"},{"label":"Token width","value":192}]},
            {"id":"embedding","label":"[CLS] + position embeddings","kind":"embedding",
             "description":"A learned class token is prepended to the patch sequence, then learned position embeddings are added. Attention receives 197 tokens.",
             "formula":"x = [CLS; patch₀; …; patch₁₉₅] + Eposition",
             "tensors":[tensor("Encoder input",traced.hidden_states[0][0,:8,:4],rows=labels[:8],selection="Tokens 0–7 · coordinates 0–3",shape=[197,192])]},
            {"id":"attention","label":"Bidirectional self-attention","kind":"attention",
             "description":"The class token and every patch attend to the entire image. This is the full recorded first head; no causal mask is applied.",
             "formula":"A = softmax(QKᵀ / √64); context = A V",
             "tensors":[tensor("Image attention · head 1",attention[0],rows=labels,columns=labels,role="attention"),
                        tensor("Head 1 context",context[:8,:4],rows=labels[:8],selection="Tokens 0–7 · head 1 coordinates 0–3",shape=[197,192])],
             "metrics":[{"label":"Heads","value":3},{"label":"Head width","value":64}]},
            {"id":"feed-forward","label":"Dense GELU feed-forward","kind":"projection",
             "description":"The same 192 → 768 → 192 MLP acts independently on each token. LayerNorm and residual paths surround the attention and MLP sublayers.",
             "formula":"MLP(x) = W₂ GELU(W₁ x + b₁) + b₂",
             "tensors":[tensor("GELU activations",observed[f"ff-{i}"][1][0,:8,:4],rows=labels[:8],selection="Tokens 0–7 · coordinates 0–3",shape=[197,768]),
                        tensor("MLP output",observed[f"down-{i}"][1][0,:8,:4],rows=labels[:8],selection="Tokens 0–7 · coordinates 0–3",shape=[197,192])]},
            {"id":"pool","label":"Read the final [CLS] token","kind":"projection",
             "description":"After all 12 encoder blocks and final LayerNorm, only the class token is sent to the classifier. This is the full model’s final class token, independent of the selected intermediate block.",
             "formula":"pooled = LayerNorm(xfinal)[CLS]",
             "tensors":[tensor("Final [CLS]",cls[:8],selection="Coordinates 0–7",shape=[192])]},
            {"id":"output","label":"ImageNet class probabilities","kind":"output",
             "description":"These are actual predictions for the synthetic shapes image. ImageNet classes describe natural objects, so they are not ground-truth shape labels.",
             "formula":"p(class) = softmax(Wclassifier · CLS + bclassifier)",
             "tensors":[tensor("Top 8 class probabilities",p,rows=[model.config.id2label[int(n)] for n in ids],selection="Top 8 of 1,000 classes; not renormalized",role="probabilities")],
             "metrics":[{"label":"Classes","value":1000}]}]
        layers.append({"index":i,"label":f"Encoder block {i+1}","operations":operations})
    for name,error in checks.items():
        assert error < 2e-5, (name,error)
    pinfo = provenance("vit",snapshot)
    pinfo["scope"] = "Full pretrained DeiT-tiny image classification. All 12 blocks, complete attention head 1, labeled activation slices. The deterministic shapes image is deliberately synthetic and ImageNet predictions are not ground-truth shape labels."
    save({"schemaVersion":1,"architecture":"vit","title":"Vision Transformer","provenance":pinfo,
          "config":{"hiddenSize":192,"intermediateSize":768,"attentionHeads":3,"headSize":64,"layers":12,"imageSize":224,"patchSize":16,"patchCount":196,"sequenceLength":197,"activation":"GELU"},
          "verification":[{"name":name,"maxAbsoluteError":error,"tolerance":2e-5} for name,error in checks.items()],
          "examples":[{"id":"colored-shapes","label":"Colored shapes","input":{"text":"Classify the image","image":image_info},"tokens":labels,"output":{"text":predictions[0]["label"],"predictions":predictions},"layers":layers}]})


def capture_vlm(snapshot):
    import torch
    from transformers import AutoProcessor, Idefics3ForConditionalGeneration
    image, image_info = make_image("vision-language")
    processor = AutoProcessor.from_pretrained(snapshot,local_files_only=True)
    model = Idefics3ForConditionalGeneration.from_pretrained(snapshot,local_files_only=True,
                  torch_dtype=torch.float32,attn_implementation="eager").eval()
    processor.image_processor.do_image_splitting = False
    prompt = "Name the colors shown in the image. Answer briefly."
    messages = [{"role":"user","content":[{"type":"image"},{"type":"text","text":prompt}]}]
    formatted = processor.apply_chat_template(messages,add_generation_prompt=True)
    # One 512×512 image, no optional crops: 1,024 patches → 64 language tokens.
    inputs = processor(text=formatted,images=[image],return_tensors="pt",
                       size={"longest_edge":512})
    generated = model.generate(**inputs,max_new_tokens=40,do_sample=False)
    completion = generated[0,inputs["input_ids"].shape[1]:]
    output_text = processor.tokenizer.decode(completion,skip_special_tokens=True)
    print("SmolVLM generated: "+output_text,flush=True)
    baseline = model(**inputs,output_attentions=True,output_hidden_states=True,use_cache=False)
    observed, hooks = {}, []
    def hook(key):
        def record(_, args, output):
            observed[key] = (args[0].detach().clone(),output.detach().clone())
        return record
    vision = model.model.vision_model
    vision.config.output_attentions = True
    vision.config.output_hidden_states = True
    def vision_hook(_, args, output):
        # Copy only head 1. Every layer still runs normally, with every head.
        observed["vision-attentions"] = [a[0,0].detach().clone() for a in output.attentions]
        observed["vision-hidden"] = output.last_hidden_state.detach().clone()
        observed["vision-embedding"] = output.hidden_states[0].detach().clone()
    hooks.append(vision.register_forward_hook(vision_hook))
    hooks.append(model.model.connector.register_forward_hook(hook("connector")))
    hooks.append(model.model.connector.modality_projection.proj.register_forward_hook(hook("projector")))
    for i, layer in enumerate(vision.encoder.layers):
        hooks.append(layer.self_attn.v_proj.register_forward_hook(hook(f"vision-v-{i}")))
        hooks.append(layer.self_attn.out_proj.register_forward_hook(hook(f"vision-o-{i}")))
    for i, layer in enumerate(model.model.text_model.layers):
        hooks.append(layer.self_attn.v_proj.register_forward_hook(hook(f"language-v-{i}")))
        hooks.append(layer.self_attn.o_proj.register_forward_hook(hook(f"language-o-{i}")))
    traced = model(**inputs,output_attentions=True,output_hidden_states=True,use_cache=False)
    for handle in hooks:
        handle.remove()
    input_ids = inputs["input_ids"][0]
    raw_tokens = processor.tokenizer.convert_ids_to_tokens(input_ids)
    image_count = 0
    tokens = []
    for token_id,token in zip(input_ids.tolist(),raw_tokens):
        if token_id == model.config.image_token_id:
            tokens.append(f"image {image_count}")
            image_count += 1
        else:
            tokens.append(token)
    assert image_count == 64
    patch_tokens = [f"patch {i//32},{i%32}" for i in range(1024)]
    query_rows = [0,1,31,32,255,511,767,1023]
    probability = torch.softmax(traced.logits[0,-1].double(),-1)
    probs, ids = probability.topk(8)
    predictions = [{"label":processor.tokenizer.decode([n]) or processor.tokenizer.convert_ids_to_tokens(n),"probability":p} for n,p in zip(ids.tolist(),probs.tolist())]
    checks = {"hookedVsUnhookedLogitMaxError":(baseline.logits-traced.logits).abs().max().item(),
        "visionAttentionRowSumMaxError":0.,"visionAttentionContextMaxError":0.,"decoderAttentionRowSumMaxError":0.,
        "decoderAttentionContextMaxError":0.,"decoderFutureAttentionMax":0.,"connectorProjectionMaxError":0.,
        "mergedImageTokensMaxError":0.,"probabilitySumError":abs(probability.sum().item()-1)}
    projected = observed["projector"][1]
    reconstruction = torch.nn.functional.linear(observed["projector"][0],model.model.connector.modality_projection.proj.weight)
    checks["connectorProjectionMaxError"] = (reconstruction-projected).abs().max().item()
    image_positions = (input_ids == model.config.image_token_id).nonzero().flatten()
    checks["mergedImageTokensMaxError"] = (traced.hidden_states[0][0,image_positions]-projected[0]).abs().max().item()
    for i in range(12):
        a = observed["vision-attentions"][i]
        values = observed[f"vision-v-{i}"][1][0].reshape(1024,12,64).transpose(0,1)[0]
        actual = observed[f"vision-o-{i}"][0][0,:,:64]
        checks["visionAttentionContextMaxError"] = max(checks["visionAttentionContextMaxError"],(a@values-actual).abs().max().item())
        checks["visionAttentionRowSumMaxError"] = max(checks["visionAttentionRowSumMaxError"],(a.sum(-1)-1).abs().max().item())
    layers = []
    for i in range(30):
        a = traced.attentions[i][0]
        # Nine query heads share three KV heads, three Q heads per KV head.
        values = observed[f"language-v-{i}"][1][0].reshape(len(tokens),3,64).transpose(0,1).repeat_interleave(3,dim=0)
        context = (a@values).transpose(0,1).reshape(len(tokens),576)
        actual = observed[f"language-o-{i}"][0][0]
        checks["decoderAttentionContextMaxError"] = max(checks["decoderAttentionContextMaxError"],(context-actual).abs().max().item())
        checks["decoderAttentionRowSumMaxError"] = max(checks["decoderAttentionRowSumMaxError"],(a.sum(-1)-1).abs().max().item())
        checks["decoderFutureAttentionMax"] = max(checks["decoderFutureAttentionMax"],a.triu(1).abs().max().item())
        # Vision processing finishes before every language block. Show its final
        # encoder block consistently; do not imply a nonexistent interleaving.
        vision_index = 11
        operations = [
            {"id":"patches","label":"Image patch embeddings","kind":"embedding",
             "description":"The 512 × 512 RGB image becomes 1,024 learned 16 × 16 patch embeddings. SigLIP supplies learned 2D position embeddings. Image splitting is disabled for this recorded example.",
             "formula":"patchᵢ = Conv16×16(image)ᵢ + positionᵢ",
             "tensors":[tensor("Vision input",observed["vision-embedding"][0,:8,:4],rows=patch_tokens[:8],selection="Patches 0–7 · coordinates 0–3",shape=[1024,768])],
             "metrics":[{"label":"Patch tokens","value":1024},{"label":"Vision width","value":768}]},
            {"id":"vision-attention","label":"SigLIP vision encoder","kind":"attention",
             "description":"The image first passes through all 12 vision blocks. This shows vision block 12, head 1: eight labeled query patches, each attending to all 1,024 image patches. This stage is complete before the selected language block runs.",
             "formula":"Avision = softmax(QKᵀ / √64)",
             "tensors":[tensor("Vision block 12 · head 1",observed["vision-attentions"][vision_index][query_rows],rows=[patch_tokens[n] for n in query_rows],columns=patch_tokens,selection="Query patch indices 0, 1, 31, 32, 255, 511, 767, 1023 · all 1,024 keys",shape=[1024,1024],role="attention")],
             "metrics":[{"label":"Vision blocks","value":12},{"label":"Vision heads","value":12}]},
            {"id":"projector","label":"Pack patches → image tokens","kind":"projection",
             "description":"Pixel shuffle groups 4 × 4 neighboring patch vectors into a 12,288D vector. A learned bias-free linear projection maps each group into the language model’s 576D space. This reduces 1,024 vision tokens to 64 image tokens.",
             "formula":"z = Wprojector · PixelShuffle4×4(vision); 1,024×768 → 64×12,288 → 64×576",
             "tensors":[tensor("Packed patches",observed["projector"][0][0,:8,:4],rows=[f"image {n}" for n in range(8)],selection="Image tokens 0–7 · packed coordinates 0–3",shape=[64,12288]),
                        tensor("Projected image tokens",projected[0,:8,:4],rows=[f"image {n}" for n in range(8)],selection="Image tokens 0–7 · coordinates 0–3",shape=[64,576])],
             "metrics":[{"label":"Image tokens","value":64},{"label":"Language width","value":576}]},
            {"id":"embedding","label":"Merge image + text tokens","kind":"embedding",
             "description":"Projected image vectors replace the 64 image placeholders in the chat prompt. Text and image tokens form one sequence; this model does not use an encoder–decoder cross-attention sublayer.",
             "formula":"x = [text embeddings; projected image tokens; text embeddings]",
             "tensors":[tensor("Merged decoder input",traced.hidden_states[0][0,:,:4],rows=tokens,selection="All prompt tokens · coordinates 0–3",shape=[len(tokens),576])]},
            {"id":"attention","label":"Image + text causal attention","kind":"attention",
             "description":"Each text token can read preceding image and text tokens. This is the full first query head of the selected language block; RoPE and grouped KV sharing are applied by the real decoder.",
             "formula":"A = softmax(RoPE(Q) RoPE(K)ᵀ / √64 + causal mask); context = A V",
             "tensors":[tensor(f"Language block {i+1} · head 1",a[0],rows=tokens,columns=tokens,role="attention"),
                        tensor("Head 1 context",actual[:8,:4],rows=tokens[:8],selection="Tokens 0–7 · head 1 coordinates 0–3",shape=[len(tokens),576])],
             "metrics":[{"label":"Query heads","value":9},{"label":"KV heads","value":3}]},
            {"id":"output","label":"Generate an image-grounded answer","kind":"output",
             "description":"The complete 30-layer decoder generated the recorded answer greedily. The probabilities below are for the first answer token, immediately after the supplied image and question.",
             "formula":"p(next token | image, text) = softmax(Wvocab · RMSNorm(hfinal))",
             "tensors":[tensor("Top first-token probabilities",probs,rows=[processor.tokenizer.convert_ids_to_tokens(int(n)) for n in ids],selection="Top 8 of 49,280 vocabulary entries; not renormalized",role="probabilities")],
             "metrics":[{"label":"Language blocks","value":30},{"label":"Generated tokens","value":len(completion)}]}]
        layers.append({"index":i,"label":f"Language block {i+1}","operations":operations})
    for name,error in checks.items():
        assert error < 3e-5,(name,error)
    pinfo = provenance("vision-language",snapshot)
    pinfo["scope"] = "Full pretrained SmolVLM-256M inference: a synthetic 512×512 image and text prompt, real greedy completion, one full prefill trace. Language attention head 1 from all 30 blocks; final vision block head 1 with eight query rows over every image patch. No image crops. Numeric vector slices explicitly labeled."
    save({"schemaVersion":1,"architecture":"vision-language","title":"Vision–language transformer","provenance":pinfo,
          "config":{"visionLayers":12,"languageLayers":30,"visionHiddenSize":768,"hiddenSize":576,"attentionHeads":9,"keyValueHeads":3,"headSize":64,"imageSize":512,"patchSize":16,"patchCount":1024,"imageTokens":64,"pixelShuffleFactor":4,"crossAttention":False},
          "verification":[{"name":name,"maxAbsoluteError":error,"tolerance":3e-5} for name,error in checks.items()],
          "examples":[{"id":"describe-shapes","label":"Name the colors","input":{"text":prompt,"image":image_info},"tokens":tokens,"output":{"text":output_text,"predictions":predictions},"generatedTokenIds":completion.tolist(),"layers":layers}]})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir",default="/tmp/moe-hf-cache")
    parser.add_argument("--model",choices=MODELS,required=True)
    args = parser.parse_args()
    import torch
    from huggingface_hub import snapshot_download
    torch.set_num_threads(4)
    torch.set_grad_enabled(False)
    torch.manual_seed(0)
    name, revision, filename, _ = MODELS[args.model]
    snapshot = Path(snapshot_download(name,revision=revision,cache_dir=args.cache_dir,
                    allow_patterns=["*.json","*.txt","*.model",filename],ignore_patterns=["onnx/*"]))
    (capture_vit if args.model == "vit" else capture_vlm)(snapshot)
    gc.collect()
